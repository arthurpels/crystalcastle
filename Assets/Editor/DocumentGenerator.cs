    // ── Helpers ──────────────────────────────────────────────────────────────

    private static void Create(string id, string title,
        DocumentData.DocumentType type, string body, string prompt)
    {
        var asset = ScriptableObject.CreateInstance<DocumentData>();
        asset.id            = id;
        asset.title         = title;
        asset.type          = type;
        asset.body          = body;
        asset.interactPrompt = prompt;

        string path = $"{OUTPUT_PATH}/{id}.asset";
        AssetDatabase.CreateAsset(asset, path);
    }

    private static void CreateMultiPart(string id, string title,
        string groupId, int partIndex, int totalParts, string body, string prompt)
    {
        var asset = ScriptableObject.CreateInstance<DocumentData>();
        asset.id            = id;
        asset.title         = title;
        asset.type          = DocumentData.DocumentType.MultiPart;
        asset.body          = body;
        asset.groupId       = groupId;
        asset.partIndex     = partIndex;
        asset.totalParts    = totalParts;
        asset.interactPrompt = prompt;

        string path = $"{OUTPUT_PATH}/{id}.asset";
        AssetDatabase.CreateAsset(asset, path);
    }
